/*
 * Primer programa en Java
 */
public class Main {
    public static void main(String[] args) {
        // Declaracion de una variable String
        String mensaje;

        // Inicializacion de la variable con un valor
        mensaje = "¡Hola, mundo!";

        // Otra forma de declarar e inicializar en una sola linea
        String saludo = "Buenos días";

        // Imprimir el valor de las variables
        System.out.println(mensaje);
        System.out.println(saludo);
    }
}
